"""
端到端集成测试：模拟器 → ATC API → Redis/Kafka 验证

测试流程：
1. 加载飞行任务模板
2. 通过 ATC API 创建飞行任务/导入航空器/申报飞行计划
3. 启动模拟器遥测注入（短时间运行验证）
4. 自动化端到端验证：API 查询 + Redis 一致性 + Kafka 消费
5. 生成 HTML 测试报告

用法:
    # 快速测试（5 架无人机，10 秒运行）
    python test_e2e_sim.py --quick

    # 完整测试（20 架，60 秒运行）
    python test_e2e_sim.py --template logistics --count 20 --duration 60

    # 仅 API 测试（不启动模拟器遥测）
    python test_e2e_sim.py --api-only
"""

