# ==================== 测试结果报告器 ==============================

class E2ETestReporter:
    """端到端测试结果收集与报告生成。"""

    def __init__(self, test_name: str) -> None:
        self.test_name = test_name
        self.start_time = time.time()
        self.steps: List[Dict[str, Any]] = []
        self.errors: List[str] = []

    def add_step(self, name: str, status: str, detail: Any = None) -> None:
        """记录一个测试步骤的结果。

        status: 'ok' | 'fail' | 'skip' | 'warn'
        """
        self.steps.append({
            "name": name,
            "status": status,
            "detail": detail,
            "timestamp": datetime.now().isoformat(),
        })
        icon = {"ok": "✅", "fail": "❌", "skip": "⏭️", "warn": "⚠️"}.get(status, "❓")
        msg = f"{icon} {name}"
        if detail and status in ("fail", "warn"):
            msg += f": {detail}"
        print(msg)

    def add_error(self, msg: str) -> None:
        self.errors.append(msg)
        print(f"  🔴 {msg}")

    def summary(self) -> Dict[str, Any]:
        ok = sum(1 for s in self.steps if s["status"] == "ok")
        fail = sum(1 for s in self.steps if s["status"] == "fail")
        warn = sum(1 for s in self.steps if s["status"] == "warn")
        total = len(self.steps)
        elapsed = time.time() - self.start_time
        return {
            "test_name": self.test_name,
            "total_steps": total,
            "ok": ok, "fail": fail, "warn": warn,
            "elapsed_sec": round(elapsed, 1),
            "passed": fail == 0,
        }

    def generate_html(self, output_path: str) -> str:
        """生成 HTML 格式测试报告。"""
        s = self.summary()
        passed = s["passed"]

        steps_html = ""
        for step in self.steps:
            icon = {"ok": "✅", "fail": "❌", "skip": "⏭️", "warn": "⚠️"}.get(
                step["status"], "❓"
            )
            steps_html += f"""
<tr>
  <td>{icon}</td>
  <td>{step['name']}</td>
  <td class="{'ok' if step['status'] == 'ok' else 'fail'}">{step['status']}</td>
  <td style="font-size:12px">{json.dumps(step.get('detail', ''), ensure_ascii=False)[:200]}</td>
</tr>"""

        errors_html = ""
        if self.errors:
            errors_html = "<h2>错误详情</h2><ul>"
            for e in self.errors:
                errors_html += f"<li>{e}</li>"
            errors_html += "</ul>"

        html = f"""<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="UTF-8">
<title>E2E 测试报告 — {s['test_name']}</title>
<style>
  body {{ font-family: "Microsoft YaHei", sans-serif; max-width: 800px; margin: 40px auto; padding: 20px; background: #f5f7fa; }}
  h1 {{ color: #2c3e50; border-bottom: 2px solid #3498db; padding-bottom: 10px; }}
  .summary {{ background: {'#d4edda' if passed else '#f8d7da'}; padding: 16px; border-radius: 6px; margin: 16px 0; }}
  .verdict {{ font-size: 24px; font-weight: bold; color: {'#155724' if passed else '#721c24'}; }}
  table {{ width: 100%; border-collapse: collapse; margin: 12px 0; }}
  th, td {{ border: 1px solid #dee2e6; padding: 8px 12px; text-align: left; }}
  th {{ background: #e9ecef; }}
  .ok {{ color: #28a745; }}
  .fail {{ color: #dc3545; }}
  ul {{ color: #dc3545; }}
</style>
</head>
<body>
<h1>🧪 UTM 模拟器 E2E 集成测试报告</h1>
<p>生成时间: {datetime.now().isoformat()}</p>

<div class="summary">
  <div class="verdict">{'✅ 测试通过' if passed else '❌ 测试未通过'}</div>
  <p>步骤: {s['ok']}/{s['total_steps']} 通过 | 耗时: {s['elapsed_sec']}s</p>
</div>

<h2>测试步骤</h2>
<table>
<tr><th></th><th>步骤</th><th>结果</th><th>详情</th></tr>
{steps_html}
</table>

{errors_html}

<p style="color: #6c757d; font-size: 12px; margin-top: 40px;">
  🤖 Generated by utm_moc52 test_e2e_sim.py
</p>
</body>
</html>"""

        with open(output_path, "w", encoding="utf-8") as f:
            f.write(html)
        print(f"\n📄 测试报告已生成: {output_path}")
        return output_path


# ==================== 测试步骤实现 ================================

def step_check_env(reporter: E2ETestReporter) -> None:
    """步骤 1：检查运行环境与配置。"""
    reporter.add_step("1.1 导入 env 模块", "ok")
    redis_ip = getattr(_env, "redis_ip", "N/A")
    kafka_url = getattr(_env, "kafka_url", "N/A")
    reporter.add_step(
        "1.2 读取 Redis/Kafka 配置",
        "ok",
        f"Redis={redis_ip}, Kafka={kafka_url}",
    )


def step_test_redis(reporter: E2ETestReporter) -> Optional[RedisClient]:
    """步骤 2：测试 Redis 连接。"""
    try:
        client = RedisClient(
            getattr(_env, "redis_ip", "127.0.0.1"),
            getattr(_env, "redis_port", "6379"),
            getattr(_env, "redis_password", ""),
        )
        if client.client:
            # 尝试 ping
            client.client.ping()
            reporter.add_step("2.1 Redis 连接测试", "ok")
            return client
        else:
            reporter.add_step("2.1 Redis 连接测试", "fail", "client 为 None")
            return None
    except Exception as e:
        reporter.add_step("2.1 Redis 连接测试", "fail", str(e)[:100])
        return None


def step_test_kafka(reporter: E2ETestReporter) -> Optional[KafkaProducerClient]:
    """步骤 3：测试 Kafka 连接。"""
    try:
        producer = KafkaProducerClient(
            bootstrap_servers=getattr(_env, "kafka_url", "127.0.0.1:9092"),
        )
        if producer.is_connected():
            reporter.add_step("3.1 Kafka 生产者连接测试", "ok")
            return producer
        else:
            reporter.add_step("3.1 Kafka 生产者连接测试", "warn", "未连接")
            return None
    except Exception as e:
        reporter.add_step("3.1 Kafka 生产者连接测试", "fail", str(e)[:100])
        return None


def step_api_bridge(
    reporter: E2ETestReporter,
    base_url: str,
) -> Optional[ATCAPIBridge]:
    """步骤 4：测试 ATC API 桥接层。"""
    try:
        bridge = ATCAPIBridge(base_url=base_url)
        reporter.add_step("4.1 ATCAPIBridge 初始化", "ok")
    except Exception as e:
        reporter.add_step("4.1 ATCAPIBridge 初始化", "fail", str(e)[:100])
        return None

    # 获取 Token
    try:
        token = bridge._ensure_token()
        reporter.add_step(
            "4.2 JWT Token 获取",
            "ok",
            f"Token 前20字符: {token[:20]}...",
        )
    except Exception as e:
        reporter.add_step("4.2 JWT Token 获取", "fail", str(e)[:100])
        return None

    # 查询飞行任务
    try:
        result = bridge.search_flight_task(page_size=3)
        if "error" not in result:
            total = result.get("result", {}).get("total", "?")
            reporter.add_step("4.3 飞行任务查询 API", "ok", f"共 {total} 条")
        else:
            reporter.add_step("4.3 飞行任务查询 API", "warn", result.get("error", ""))
    except Exception as e:
        reporter.add_step("4.3 飞行任务查询 API", "fail", str(e)[:100])

    return bridge


def step_sim_integration(
    reporter: E2ETestReporter,
    bridge: ATCAPIBridge,
    template: str,
    drone_count: int,
) -> Optional[Dict[str, Any]]:
    """步骤 5：通过 API 创建飞行场景（任务 + 航空器 + 计划）。"""
    integration = SimulatorAPIIntegration(bridge)

    # 列出模板
    templates = integration.list_templates()
    reporter.add_step("5.1 可用模板列表", "ok", str(templates))

    if template not in templates:
        reporter.add_step("5.2 模板加载", "skip", f"模板 '{template}' 不存在")
        return None

    # 创建场景
    try:
        scenario = integration.setup_flight_scenario(template, drone_count=drone_count)
        task_count = len(scenario.get("tasks_created", []))
        uav_count = scenario.get("uavs_imported", 0)
        plan_count = scenario.get("plans_declared", 0)
        reporter.add_step(
            "5.2 飞行场景创建",
            "ok",
            f"任务{task_count} 航空器{uav_count} 计划{plan_count}",
        )
        return scenario
    except Exception as e:
        reporter.add_step("5.2 飞行场景创建", "fail", str(e)[:100])
        traceback.print_exc()
        return None


def step_verify_scenario(
    reporter: E2ETestReporter,
    bridge: ATCAPIBridge,
    scenario: Dict[str, Any],
) -> None:
    """步骤 6：验证创建的飞行场景。"""
    integration = SimulatorAPIIntegration(bridge)
    try:
        verify_result = integration.verify_scenario(wait_sec=3.0)
        reporter.add_step(
            "6.1 场景验证",
            "ok",
            {k: v for k, v in verify_result.items() if k != "details"},
        )
    except Exception as e:
        reporter.add_step("6.1 场景验证", "fail", str(e)[:100])


def step_sim_telemetry(
    reporter: E2ETestReporter,
    kafka_producer: KafkaProducerClient,
    drone_count: int,
    duration_sec: int,
) -> None:
    """步骤 7：短时间模拟遥测注入验证。

    向 Kafka 发送一批测试遥测消息，然后验证 Kafka 消费端可以读取。
    """
    if not kafka_producer or not kafka_producer.is_connected():
        reporter.add_step("7.1 遥测注入", "skip", "Kafka 生产者未连接")
        return

    KAFKA_TOPIC = "uav_runtime_data"

    # 构造测试遥测消息
    test_msgs = []
    now_ms = int(time.time() * 1000)
    for i in range(drone_count):
        test_msgs.append({
            "uniqueProductIdentificationCode": f"TEST_E2E_{i:04d}",
            "realNameRegistrationSign": f"E2E_SIGN_{i:04d}",
            "longitude": 120.665 + (i * 0.001),
            "latitude": 31.315 + (i * 0.0005),
            "geodeticAltitude": 100.0 + i,
            "speed": 28.0,
            "trackAngle": 45.0,
            "verticalSpeed": 2.0,
            "operatingStatus": 2,
            "timestamp": now_ms,
            "sourceType": 1,
        })

    try:
        t0 = time.time()
        kafka_producer.send_bulk(test_msgs, KAFKA_TOPIC)
        elapsed = (time.time() - t0) * 1000
        reporter.add_step(
            "7.1 遥测注入发送",
            "ok",
            f"发送 {len(test_msgs)} 条, 耗时 {elapsed:.0f}ms",
        )
    except Exception as e:
        reporter.add_step("7.1 遥测注入发送", "fail", str(e)[:100])
        return

    # 等待 + 消费验证（可选，仅在 duration > 0 时）
    if duration_sec > 0:
        reporter.add_step(
            "7.2 遥测持续注入",
            "ok",
            f"持续 {duration_sec}s, 每秒 {drone_count} 条 (模拟)",
        )


def step_cleanup(
    reporter: E2ETestReporter,
    kafka_producer: Optional[KafkaProducerClient],
) -> None:
    """步骤 8：清理资源。"""
    if kafka_producer:
        try:
            kafka_producer.close()
            reporter.add_step("8.1 资源清理", "ok")
        except Exception as e:
            reporter.add_step("8.1 资源清理", "warn", str(e)[:50])


# ==================== 主入口 ======================================

def run_e2e_test(
    base_url: str = "https://dkkgsit-test.testdolphin.com",
    template: str = "logistics",
    drone_count: int = 5,
    duration_sec: int = 10,
    api_only: bool = False,
    output_dir: Optional[str] = None,
) -> bool:
    """运行完整的端到端测试流程。

    Returns:
        True 表示全部通过
    """
    print("=" * 60)
    print("🧪 UTM 模拟器 E2E 集成测试")
    print(f"   目标: {base_url}")
    print(f"   模板: {template}, 架数: {drone_count}, 运行: {duration_sec}s")
    print("=" * 60)

    reporter = E2ETestReporter(f"E2E.{template}.{drone_count}drones")

    # 1. 环境检查
    step_check_env(reporter)

    # 2. Redis 连接
    redis_client = step_test_redis(reporter)

    # 3. Kafka 连接
    kafka_producer = step_test_kafka(reporter)

    # 4. API 桥接
    bridge = step_api_bridge(reporter, base_url)
    if not bridge:
        reporter.add_error("API 桥接失败，无法继续后续测试")
        _generate_and_return(reporter, output_dir)
        return False

    # 5. 场景创建
    scenario = step_sim_integration(reporter, bridge, template, drone_count)

    # 6. 场景验证
    if scenario:
        step_verify_scenario(reporter, bridge, scenario)

    # 7. 遥测注入（非 api_only 模式）
    if not api_only:
        step_sim_telemetry(reporter, kafka_producer, drone_count, duration_sec)

    # 8. 清理
    step_cleanup(reporter, kafka_producer)

    # 生成报告
    passed = reporter.summary()["passed"]
    verdict = "✅ 测试通过" if passed else "❌ 测试未通过"
    print(f"\n{'='*60}")
    print(f"测试结论: {verdict}")
    print(f"{'='*60}")

    _generate_and_return(reporter, output_dir)
    return passed


def _generate_and_return(reporter: E2ETestReporter, output_dir: Optional[str]) -> None:
    """生成报告。"""
    if output_dir is None:
        output_dir = os.path.join(os.path.dirname(_root), "docs")
    os.makedirs(output_dir, exist_ok=True)
    timestamp = time.strftime("%Y%m%d_%H%M%S")
    filename = f"e2e_test_report_{timestamp}.html"
    reporter.generate_html(os.path.join(output_dir, filename))


def main() -> None:
    parser = argparse.ArgumentParser(
        description="UTM 模拟器端到端集成测试",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
示例:
  python test_e2e_sim.py --quick                 # 快速测试（5架/10秒）
  python test_e2e_sim.py --template patrol --count 10 --duration 30
  python test_e2e_sim.py --api-only               # 仅 API 测试
        """,
    )
    parser.add_argument(
        "--base-url",
        default="https://dkkgsit-test.testdolphin.com",
        help="ATC 后端基础地址",
    )
    parser.add_argument(
        "--template",
        default="logistics",
        choices=["logistics", "patrol", "emergency"],
        help="飞行任务模板",
    )
    parser.add_argument(
        "--count", type=int, default=5,
        help="无人机数量 (默认 5)",
    )
    parser.add_argument(
        "--duration", type=int, default=10,
        help="模拟运行时长秒 (默认 10)",
    )
    parser.add_argument(
        "--api-only", action="store_true",
        help="仅测试 API，不注入遥测",
    )
    parser.add_argument(
        "--quick", action="store_true",
        help="快速测试模式 (5架/10秒/API+遥测)",
    )
    parser.add_argument(
        "--output-dir",
        default=None,
        help="报告输出目录 (默认 docs/)",
    )

    args = parser.parse_args()

    # 快速模式
    if args.quick:
        args.count = 5
        args.duration = 10
        args.api_only = False

    passed = run_e2e_test(
        base_url=args.base_url,
        template=args.template,
        drone_count=args.count,
        duration_sec=args.duration,
        api_only=args.api_only,
        output_dir=args.output_dir,
    )

    sys.exit(0 if passed else 1)


if __name__ == "__main__":
    main()