# ── 确定性生成新增标识符（hash-based，保证每次结果相同）─────────────────
def _generate_batch(batch_no: int, count: int, prefix: str) -> List[Tuple[str, str]]:
    """按批次生成固定标识符，使用 hashlib 保证确定性。"""
    result = []
    for i in range(1, count + 1):
        # seq: 4 位数字
        seq_str = f"{i:04d}"
        # suffix: 8 位，由 hashlib 确定性生成
        raw = hashlib.sha256(f"{prefix}_{seq_str}_{batch_no}".encode()).hexdigest()
        suffix = raw.upper()[:8]
        uid = f"{prefix}{seq_str}{suffix}"  # 8 + 4 + 8 = 20 位
        reg_sign = f"UAS{batch_no:02d}{prefix}{i:03d}"
        result.append((uid, reg_sign))
    return result


